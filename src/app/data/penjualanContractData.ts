/**
 * Helper to build EnhancedTable Columns for a given contract schema
 */
export function buildTableColumnsFromContract(columnList: readonly string[]): Column[] {
  return columnList.map((colName) => {
    const isDate = colName.toLowerCase().includes("tanggal");
    const isFilterableText =
      colName === "Plat No" ||
      colName === "Nama Customer" ||
      colName === "Nama" ||
      colName === "Jenis Pengurusan" ||
      colName === "No Invoice" ||
      colName === "Tanda Terima" ||
      colName === "TTB BPKB";

    const isR4R2 = colName === "R4 / R2";
    const isJenisBayar = colName === "Jenis Bayar";
    const isStatus = colName === "Status";
    const isStatusBPKB = colName === "Status BPKB";
    const isBPKB = colName === "BPKB";

    const baseCol: Column = {
      key: colName,
      label: colName, // Exact contract label
    };

    if (isDate) {
      baseCol.filterable = true;
      baseCol.filterType = "text";
    } else if (isR4R2) {
      baseCol.filterable = true;
      baseCol.filterType = "select";
      baseCol.filterOptions = ["R4", "R2"];
    } else if (isJenisBayar) {
      baseCol.filterable = true;
      baseCol.filterType = "select";
      baseCol.filterOptions = ["Transfer", "Cash", "Tempo"];
    } else if (isStatus) {
      baseCol.filterable = true;
      baseCol.filterType = "select";
      baseCol.filterOptions = ["Selesai", "Proses", "Pending", "Belum Bayar", "Kurang Bayar"];
    } else if (isStatusBPKB) {
      baseCol.filterable = true;
      baseCol.filterType = "select";
      baseCol.filterOptions = ["Selesai", "Proses", "-"];
    } else if (isBPKB) {
      baseCol.filterable = true;
      baseCol.filterType = "select";
      baseCol.filterOptions = ["Ada", "Belum", "-"];
    } else if (isFilterableText) {
      baseCol.filterable = true;
      baseCol.filterType = "text";
    }

    return baseCol;
  });
}

/**
 * Helper to build FieldConfig for add/edit pages matching exact contract
 */
export function buildFieldsFromContract(columnList: readonly string[]): FieldConfig[] {
  return columnList.map((colName) => {
    const isDate = colName.toLowerCase().includes("tanggal");
    const isNumber =
      colName.toLowerCase().includes("uang") ||
      colName.toLowerCase().includes("profit") ||
      colName.toLowerCase().includes("cashback");

    if (isDate) {
      return { key: colName, label: colName, type: "date" };
    }
    if (colName === "R4 / R2") {
      return { key: colName, label: colName, type: "select", options: ["R4", "R2"] };
    }
    if (colName === "Jenis Bayar") {
      return { key: colName, label: colName, type: "select", options: ["Transfer", "Cash", "Tempo"] };
    }
    if (colName === "Bank Uang Keluar") {
      return { key: colName, label: colName, type: "select", options: ["BCA", "Mandiri", "BRI", "BNI", "Kas Kantor", "Kas Messenger", "Cash"] };
    }
    if (colName === "Status") {
      return { key: colName, label: colName, type: "select", options: ["Selesai", "Proses", "Pending", "Belum Bayar", "Kurang Bayar"] };
    }
    if (colName === "BPKB") {
      return { key: colName, label: colName, type: "select", options: ["Ada", "Belum"] };
    }
    if (colName === "Status BPKB") {
      return { key: colName, label: colName, type: "select", options: ["Selesai", "Proses"] };
    }
    if (isNumber) {
      return { key: colName, label: colName, type: "number", placeholder: "0" };
    }
    return { key: colName, label: colName, type: "text" };
  });
}

